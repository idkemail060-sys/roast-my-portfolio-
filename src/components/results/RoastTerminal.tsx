import React, { useState } from 'react';
import { 
  Flame, 
  Copy, 
  Check, 
  Terminal, 
  Sparkles, 
  FileText, 
  Share2 
} from 'lucide-react';
import { PortfolioReview } from '../../types';

interface RoastTerminalProps {
  review: PortfolioReview;
}

export const RoastTerminal: React.FC<RoastTerminalProps> = ({ review }) => {
  const [copiedRoast, setCopiedRoast] = useState(false);
  const [copiedReport, setCopiedReport] = useState(false);

  const handleCopyRoast = () => {
    navigator.clipboard.writeText(`"${review.roast}" — Roast My Portfolio audit for ${review.domain}`);
    setCopiedRoast(true);
    setTimeout(() => setCopiedRoast(false), 2200);
  };

  const handleCopyMarkdownReport = () => {
    const scores = review.scores || {
      uiUx: review.uiUx ?? 7.0,
      performance: review.performance ?? 7.0,
      accessibility: review.accessibility ?? 7.0,
      content: review.content ?? 7.0,
    };
    const overall = review.overallScore ?? 7.0;

    const markdown = `# Portfolio Audit Report: ${review.domain}
URL: ${review.url}
Overall Score: ${overall.toFixed(1)} / 10.0
Date: ${new Date(review.createdAt).toLocaleDateString()}

## Scores Breakdown
- UI / UX Polish: ${scores.uiUx.toFixed(1)} / 10.0 (30% weight)
- Performance Signals: ${scores.performance.toFixed(1)} / 10.0 (25% weight)
- Accessibility & DOM: ${scores.accessibility.toFixed(1)} / 10.0 (25% weight)
- Content & Narrative: ${scores.content.toFixed(1)} / 10.0 (20% weight)

## The Roast
> "${review.roast}"

## Executive Summary
${review.summary}

## Confirmed Strengths
${(review.strengths || []).map((s) => `- ${s}`).join('\n')}

## Issues & Technical Findings
${(review.issues || []).map((iss) => `- [${iss.severity.toUpperCase()}] ${iss.title}: ${iss.description}`).join('\n')}

## Recommended Action Items
${(review.suggestions || []).map((sug, i) => `${i + 1}. [${sug.impact.toUpperCase()} IMPACT] ${sug.title}: ${sug.description}`).join('\n')}

---
Generated by Roast My Portfolio (Gemini 2.5 Flash Developer Engine)
`;

    navigator.clipboard.writeText(markdown);
    setCopiedReport(true);
    setTimeout(() => setCopiedReport(false), 2500);
  };

  return (
    <div className="relative rounded-2xl border border-neutral-750 bg-neutral-900/90 shadow-[0_20px_50px_rgba(0,0,0,0.8),0_0_30px_rgba(249,115,22,0.08)] overflow-hidden backdrop-blur-xl transition-all duration-300">
      {/* Terminal Title Bar */}
      <div className="border-b border-neutral-800 px-4 sm:px-6 py-3.5 bg-neutral-950/90 flex items-center justify-between">
        <div className="flex items-center gap-3">
          <div className="flex items-center gap-1.5" aria-hidden="true">
            <span className="w-3 h-3 rounded-full bg-rose-500/80 border border-rose-600/50" />
            <span className="w-3 h-3 rounded-full bg-amber-500/80 border border-amber-600/50" />
            <span className="w-3 h-3 rounded-full bg-emerald-500/80 border border-emerald-600/50" />
          </div>
          <div className="flex items-center gap-2 text-xs font-mono text-neutral-400">
            <Terminal className="w-3.5 h-3.5 text-orange-400" />
            <span className="text-neutral-500">~/verdict/</span>
            <span className="text-neutral-200 font-semibold">{review.domain}.sh</span>
          </div>
        </div>

        {/* Quick Actions in Header with smooth micro-interactions */}
        <div className="flex items-center gap-2">
          <button
            onClick={handleCopyRoast}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-neutral-900/90 border border-neutral-800 hover:border-neutral-700 active:scale-95 text-xs font-mono text-neutral-300 hover:text-neutral-100 transition-all cursor-pointer focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-orange-500 shadow-sm"
            title="Copy roast quote"
            aria-label="Copy roast quote to clipboard"
          >
            {copiedRoast ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
            <span className="hidden sm:inline">{copiedRoast ? 'Roast Copied!' : 'Copy Roast'}</span>
          </button>

          <button
            onClick={handleCopyMarkdownReport}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-neutral-900/90 border border-neutral-800 hover:border-neutral-700 active:scale-95 text-xs font-mono text-neutral-300 hover:text-neutral-100 transition-all cursor-pointer focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-orange-500 shadow-sm"
            title="Copy entire audit as Markdown"
            aria-label="Copy entire markdown audit report"
          >
            {copiedReport ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <FileText className="w-3.5 h-3.5" />}
            <span className="hidden sm:inline">{copiedReport ? 'Report Copied!' : 'Copy Markdown'}</span>
          </button>
        </div>
      </div>

      {/* Terminal Content Body */}
      <div className="p-6 sm:p-8 space-y-6 bg-gradient-to-b from-neutral-900/80 via-neutral-925/90 to-neutral-950">
        
        {/* Layered 3D Roast Quote Box */}
        <div className="relative rounded-xl border border-orange-500/30 bg-gradient-to-br from-orange-500/10 via-neutral-950/80 to-amber-500/5 p-6 shadow-[0_10px_30px_rgba(249,115,22,0.1)] overflow-hidden">
          {/* Subtle glowing ambient orb */}
          <div className="absolute top-0 right-0 w-48 h-48 bg-orange-500/10 rounded-full blur-2xl pointer-events-none -z-10" />

          <div className="flex items-center gap-2 text-xs font-mono text-orange-400 font-semibold mb-4">
            <span className="p-1 rounded-md bg-orange-500/20 border border-orange-500/30 inline-flex">
              <Flame className="w-4 h-4 text-orange-400 fill-orange-400/30 animate-pulse" />
            </span>
            <span className="tracking-wider">THE CONSTRUCTIVE ROAST</span>
          </div>

          <div className="relative pl-5 py-1 border-l-4 border-orange-500">
            <blockquote className="text-lg sm:text-2xl font-mono text-neutral-100 font-bold leading-relaxed tracking-tight">
              "{review.roast}"
            </blockquote>
          </div>
        </div>

        {/* AI Executive Summary Box with Layered Depth */}
        <div className="p-5 sm:p-6 rounded-xl border border-neutral-800 bg-neutral-950/80 shadow-md space-y-2.5">
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-2 text-xs font-mono font-bold text-neutral-200">
              <Sparkles className="w-3.5 h-3.5 text-amber-400" />
              <span>EXECUTIVE AUDIT SUMMARY</span>
            </div>
            <span className="text-[10px] font-mono text-neutral-400 px-2.5 py-0.5 rounded-full bg-neutral-900 border border-neutral-800">
              Gemini 2.5 Flash • Technical Reviewer
            </span>
          </div>
          <p className="text-sm text-neutral-300 font-sans leading-relaxed">
            {review.summary}
          </p>
        </div>

      </div>
    </div>
  );
};
